"""PostgreSQL persistence layer (asyncpg): schema, pooled connections, transactions, batched retention purge.

Conventions for every caller:
- Statements are written with `?` placeholders; `translate()` turns them into `$n` in order, so dynamic builders stay
  order-safe. A `?` never appears inside a SQL literal here, and the jsonb `?` operators are refused on purpose.
- Every `str` parameter has NUL bytes replaced (`clean()`): PostgreSQL text refuses them, SQLite accepted them.
- Inserts that need the new id say `RETURNING id` and go through `fetchval()`; `execute()` returns rows affected.
- Inside `transaction()` use only the `tx.*` methods: `db.*` runs on another pooled connection.
- `execute()` with no parameters runs the simple-query protocol, which accepts several statements; it therefore
  refuses a `;` (the schema runner in `connect()` is the only multi-statement path).
"""

